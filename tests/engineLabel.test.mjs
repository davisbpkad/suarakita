import assert from 'node:assert/strict';
import { engineLabel, fallbackLabel } from '../resources/js/lib/engineLabel.mjs';
assert.equal(engineLabel({ engine: 'groq', method: 'llm_ai', modelUsed: 'test-model' }), 'Groq · test-model');
assert.equal(engineLabel({ engine: 'gemini', method: 'llm_ai' }), 'Gemini');
assert.equal(engineLabel({ engine: 'local' }), 'Mesin lokal');
assert.equal(engineLabel({}), 'Menunggu hasil');
assert.match(fallbackLabel({ attempts: [{ provider: 'gemini', outcome: 'rate_limited' }] }), /batas penggunaan/);
assert.match(fallbackLabel({ attempts: [{ provider: 'groq', outcome: 'access_denied' }] }), /akses ditolak/);
assert.equal(fallbackLabel({ attempts: [{ provider: 'gemini', outcome: 'success' }] }), '');
console.log('Label mesin: 7 assertion lulus');
